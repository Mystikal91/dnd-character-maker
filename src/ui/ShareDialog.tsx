import { signal } from "@preact/signals";
import { useEffect, useRef, useState } from "preact/hooks";
import qrcode from "qrcode-generator";
import { character } from "../app/store";
import { ui } from "../i18n/ui";
import { QR_MAX_BYTES, shareUrl } from "../storage/share";

/** Whether the share dialog is open. */
export const shareOpen = signal(false);

function qrSvg(text: string): string | undefined {
  if (new TextEncoder().encode(text).length > QR_MAX_BYTES) return undefined;
  try {
    const code = qrcode(0, "L");
    code.addData(text);
    code.make();
    return code.createSvgTag({ cellSize: 4, margin: 3, scalable: true });
  } catch {
    return undefined;
  }
}

/** A link that carries the whole character, with a QR code of it. Mount once near the root. */
export function ShareDialog() {
  const dialog = useRef<HTMLDialogElement>(null);
  const field = useRef<HTMLInputElement>(null);
  const [url, setUrl] = useState("");
  const [copied, setCopied] = useState(false);
  const open = shareOpen.value;

  useEffect(() => {
    const el = dialog.current;
    if (!el) return;
    if (open && !el.open) el.showModal();
    if (!open && el.open) el.close();
  }, [open]);

  // The link is rebuilt each time the dialog opens, so it always matches the current character.
  useEffect(() => {
    if (!open) return;
    setCopied(false);
    let current = true;
    shareUrl(character.value, location.href).then((link) => {
      if (current) setUrl(link);
    });
    return () => {
      current = false;
    };
  }, [open]);

  const svg = url ? qrSvg(url) : undefined;
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(url);
      setCopied(true);
    } catch {
      field.current?.select();
    }
  };
  const canShare = typeof navigator !== "undefined" && "share" in navigator;

  return (
    // biome-ignore lint/a11y/useKeyWithClickEvents: clicking the backdrop is a mouse shortcut; Escape and the Close button are the keyboard ways out
    <dialog
      ref={dialog}
      class="spell-dialog share-dialog"
      onClose={() => {
        shareOpen.value = false;
      }}
      onClick={(e) => {
        if (e.target === e.currentTarget) shareOpen.value = false;
      }}
    >
      {open && (
        <div class="spell-dialog-body">
          <button
            type="button"
            class="secondary close"
            onClick={() => {
              shareOpen.value = false;
            }}
          >
            {ui("share.close")}
          </button>
          <h3>{ui("share.title")}</h3>
          <p class="muted">{ui("share.intro")}</p>
          <label class="field">
            <span>{ui("share.link")}</span>
            <input
              ref={field}
              type="text"
              readOnly
              value={url}
              onFocus={(e) => e.currentTarget.select()}
            />
          </label>
          <div class="share-actions">
            <button type="button" onClick={() => void copy()} disabled={!url}>
              {copied ? ui("share.copied") : ui("share.copy")}
            </button>
            {canShare && (
              <button
                type="button"
                class="secondary"
                disabled={!url}
                onClick={() =>
                  void navigator
                    .share({ title: character.value.name || ui("sheet.unnamed"), url })
                    .catch(() => undefined)
                }
              >
                {ui("share.native")}
              </button>
            )}
          </div>
          {svg ? (
            <div class="qr" role="img" aria-label={ui("share.qr")}>
              {/* biome-ignore lint/security/noDangerouslySetInnerHtml: the SVG is generated by the QR library from our own link */}
              <div dangerouslySetInnerHTML={{ __html: svg }} />
            </div>
          ) : (
            url && <p class="note">{ui("share.tooLong")}</p>
          )}
        </div>
      )}
    </dialog>
  );
}
